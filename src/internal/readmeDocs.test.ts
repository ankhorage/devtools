import { describe, expect, it } from 'bun:test';

import { getReadmeDocumentationErrors } from './readmeDocs.js';

describe('README documentation validation', () => {
  it('accepts a README that documents the canonical generated surface', () => {
    expect(
      getReadmeDocumentationErrors(createCanonicalReadmeFixture(), 'Ankhorage Devtools'),
    ).toEqual([]);
  });

  it('reports missing canonical usage references', () => {
    expect(getReadmeDocumentationErrors('ankh devtools --help', 'Ankhorage Devtools')).toContain(
      'README.md is missing required documentation snippet: Standalone package ESLint configuration',
    );
  });
});

it('rejects the obsolete package title and documentation chapter', () => {
  const legacy = createCanonicalReadmeFixture()
    .replace('# Ankhorage Devtools', '# @ankhorage/devtools')
    .replace('## Documentation', '## Generated documentation');

  expect(getReadmeDocumentationErrors(legacy, 'Ankhorage Devtools')).toEqual([
    'README.md is missing required documentation snippet: # Ankhorage Devtools',
    'README.md is missing required documentation snippet: ## Documentation',
  ]);
});

/*** Build one README fixture containing every required canonical documentation marker. */
function createCanonicalReadmeFixture(): string {
  return [
    '<!-- This file is generated by Paradox. Do not edit manually. -->',
    '# Ankhorage Devtools',
    '## Usage',
    'ankh devtools --help',
    'Standalone package ESLint configuration',
    'export default createConfig({',
    '## Documentation',
    'paradox/index.html',
  ].join('\n');
}
